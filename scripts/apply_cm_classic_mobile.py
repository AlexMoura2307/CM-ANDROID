"""Apply a reversible mobile touch/viewport baseline to the CM upstream app."""
from pathlib import Path
import sys

root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("upstream")
index = root / "index.html"
if not index.is_file():
    raise SystemExit(f"Arquivo não encontrado: {index}")
source = index.read_text(encoding="utf-8")
marker = 'id="cm-classic-mobile"'
style = """<style id="cm-classic-mobile">
@media (max-width: 640px) {
  html, body, #root { width: 100%; max-width: 100%; min-width: 0; }
  body { overflow-x: hidden; -webkit-text-size-adjust: 100%; }
  button, select, input[type="checkbox"], input[type="radio"] { touch-action: manipulation; }
  button, select { min-height: 40px; }
  input[type="checkbox"], input[type="radio"] { min-width: 16px; min-height: 16px; }
  table { max-width: 100%; }
}
</style>"""
if marker in source:
    print("Já aplicado; nenhuma alteração.")
elif "</head>" not in source:
    raise SystemExit("HTML inválido: </head> não encontrado")
else:
    index.write_text(source.replace("</head>", style + "\n</head>", 1), encoding="utf-8")
    print("Base de interface CM Clássico Mobile aplicada.")


# Replace the tabbed profile generated by prepare_cm.py with a compact layout.
profile = root / "src/components/playerProfile/PlayerProfile.tsx"
body = profile.read_text(encoding="utf-8")
marker = "cm-classic-history-toggle"
if marker not in body:
    start = body.find('  const profileSections = [')
    end = body.find('  return (\n    <div>', start)
    if start < 0 or end < 0:
        raise SystemExit("Profile section definition not found")
    body = body[:start] + body[end:]
    start = body.find('      <div className="mb-4 overflow-x-auto pb-1">')
    end = body.find('      {bidTarget && (', start)
    if start < 0 or end < 0:
        raise SystemExit("Profile content boundary not found")
    old = body[start:end]
    def component(name):
        import re
        found = re.search(r'<'+name+r'\b[\s\S]*?/>', old)
        if not found:
            raise SystemExit("Missing profile component: " + name)
        return found.group(0)
    attrs = component("PlayerProfileAttributesCard")
    contract = component("PlayerProfileContractCard")
    history = [component(n) for n in ("PlayerProfileCareerHistoryCard", "PlayerProfileAdvancedStatsCard", "PlayerProfileSeasonStatsCard", "PlayerProfileMovementHistoryCard")]
    # Recent matches are optional and already guarded by the original implementation.
    recent = '<PlayerProfileRecentMatchesCard matches={recentMatches} t={t} />'
    new = (
        '      {/* cm-classic-history-toggle: compact player profile */}\n'
        + '      <div className="space-y-3">\n'
        + attrs + '\n' + contract + '\n'
        + '''        <Card>
          <CardHeader>{t("playerProfile.roleAndDuty")}</CardHeader>
          <CardBody>
            <div className="grid gap-3 sm:grid-cols-2">
              <div className="rounded-xl border border-gray-100 bg-gray-50 p-3 dark:border-navy-600 dark:bg-navy-700/40">
                <p className="text-[10px] font-heading font-bold uppercase tracking-wider text-gray-400 dark:text-gray-500">
                  {t("tactics.playerRoleLabel")}
                </p>
                <p className="mt-1 font-heading font-bold text-gray-800 dark:text-gray-100">
                  {t(`tactics.playerRoles.${currentTacticalRole}`, currentTacticalRole)}
                </p>
              </div>

              {isOwnClub && onGameUpdate ? (
                <div className="rounded-xl border border-gray-100 bg-gray-50 p-3 dark:border-navy-600 dark:bg-navy-700/40">
                  <p className="mb-2 text-[10px] font-heading font-bold uppercase tracking-wider text-gray-400 dark:text-gray-500">
                    {t("playerProfile.changeRole")}
                  </p>
                  <Select
                    selectSize="sm"
                    value={currentTacticalRole}
                    onChange={(e) => {
                      void handleTacticalRoleChange(e.target.value as PlayerRole);
                    }}
                    aria-label={t("tactics.playerRoleLabel")}
                  >
                    {tacticalRoleOptions.map((role) => (
                      <option key={role} value={role}>
                        {t(`tactics.playerRoles.${role}`, role)}
                      </option>
                    ))}
                  </Select>
                </div>
              ) : null}
            </div>
          </CardBody>
        </Card>
'''+ '\n'
        + '      </div>\n'
        + '      {contractActionError ? <p role="alert" className="mt-2 text-sm text-red-600">{contractActionError}</p> : null}\n'
        + '      <button type="button" className="mt-3 w-full rounded border px-3 py-2 text-sm" onClick={() => setActiveProfileSection(activeProfileSection === "career" ? "attributes" : "career")} aria-expanded={activeProfileSection === "career"}>{activeProfileSection === "career" ? "Ocultar histórico" : "Histórico"}</button>\n'
        + '      {activeProfileSection === "career" && <div className="mt-3 space-y-3">\n'
        + '\n'.join(history) + '\n'
        + '      {recentMatches.length > 0 ? ' + recent + ' : null}\n'
        + '      </div>}\n'
    )
    body = body[:start] + new + body[end:]
    body = body.replace('import { ArrowLeft, BarChart3, Briefcase, CalendarDays, Clock3, History, ListChecks, SlidersHorizontal } from "lucide-react";', 'import { ArrowLeft } from "lucide-react";')
    # Fail the build if the compact view loses player actions or club permissions.
    required = (
        'cm-classic-history-toggle',
        'PlayerProfileAttributesCard',
        'PlayerProfileContractCard',
        'PlayerProfileCareerHistoryCard',
        'PlayerProfileMovementHistoryCard',
        'isOwnClub && onGameUpdate',
        'handleTacticalRoleChange',
        'tacticalRoleOptions.map',
        'contractActionError',
        '{bidTarget && (',
    )
    missing = [item for item in required if item not in body]
    if missing:
        raise SystemExit("CM compact profile regression: " + ", ".join(missing))
    if body.count('cm-classic-history-toggle') != 1:
        raise SystemExit("CM compact profile duplicated")
    profile.write_text(body, encoding="utf-8")
    print("CM classic profile applied after existing CM tab customization")
